#!/usr/bin/env python3
"""Generate src/syscall/sysnum32.c: the i386 -> x86_64 syscall number map.

Reads the kernel's asm/unistd_32.h and asm/unistd_64.h (from linux-libc-dev)
and emits a table mapping every i386 syscall klee could care about to the
x86_64 number its handlers are registered under.  i386-only spellings
(stat64, getuid32, fcntl64, ...) are folded onto their x86_64 equivalents;
entries whose user-visible struct layout differs from the x86_64 one are
flagged so exit handlers leave the buffer alone.

Run from the repository root:
    python3 scripts/gen_sysnum32.py > src/syscall/sysnum32.c
"""
import re
import sys

H32 = "/usr/include/x86_64-linux-gnu/asm/unistd_32.h"
H64 = "/usr/include/x86_64-linux-gnu/asm/unistd_64.h"

# i386 name -> (x86_64 name, flags).  Flags:
#   OLDSTRUCT  the buffer layout is a legacy one; do not rewrite it
#   DEMUX      multiplexer that klee splits into the real call at runtime
ALIASES = {
    "stat64": ("stat", ""), "lstat64": ("lstat", ""), "fstat64": ("fstat", ""),
    "fstatat64": ("newfstatat", ""),
    "oldstat": ("stat", "OLDSTRUCT"), "oldlstat": ("lstat", "OLDSTRUCT"),
    "oldfstat": ("fstat", "OLDSTRUCT"),
    "chown32": ("chown", ""), "lchown32": ("lchown", ""), "fchown32": ("fchown", ""),
    "getuid32": ("getuid", ""), "geteuid32": ("geteuid", ""),
    "getgid32": ("getgid", ""), "getegid32": ("getegid", ""),
    "getgroups32": ("getgroups", ""), "setgroups32": ("setgroups", ""),
    "getresuid32": ("getresuid", ""), "getresgid32": ("getresgid", ""),
    "setuid32": ("setuid", ""), "setgid32": ("setgid", ""),
    "setreuid32": ("setreuid", ""), "setregid32": ("setregid", ""),
    "setresuid32": ("setresuid", ""), "setresgid32": ("setresgid", ""),
    "setfsuid32": ("setfsuid", ""), "setfsgid32": ("setfsgid", ""),
    "fcntl64": ("fcntl", ""), "truncate64": ("truncate", ""),
    "ftruncate64": ("ftruncate", ""), "statfs64": ("statfs", ""),
    "fstatfs64": ("fstatfs", ""), "umount": ("umount2", ""),
    "waitpid": ("wait4", ""), "ugetrlimit": ("getrlimit", ""),
    "utimensat_time64": ("utimensat", ""), "sendfile64": ("sendfile", ""),
    "olduname": ("uname", "OLDSTRUCT"), "oldolduname": ("uname", "OLDSTRUCT"),
    "socketcall": (None, "DEMUX"), "ipc": (None, "DEMUX"),
}

# i386 syscalls that share a name with x86_64 but use a 16-bit uid ABI or an
# old struct; they map by name, flagged so handlers skip struct rewriting.
OLDSTRUCT_SAME_NAME = {"stat", "lstat", "fstat"}


LOOKUP = """#define SYS32_INDEX_SIZE 512

static int16_t i386_to_x64[SYS32_INDEX_SIZE];
static uint8_t i386_flags[SYS32_INDEX_SIZE];
static int index_ready;

static void build_index(void)
{
    for (size_t i = 0; i < SYS32_INDEX_SIZE; i++)
        i386_to_x64[i] = -1;
    for (size_t i = 0; i < klee_sysnum32_table_len; i++) {
        const KleeSysnum32Entry *e = &klee_sysnum32_table[i];
        if (e->nr32 < SYS32_INDEX_SIZE) {
            i386_to_x64[e->nr32] = e->nr64;
            i386_flags[e->nr32] = e->flags;
        }
    }
    index_ready = 1;
}

int klee_sysnum_i386_to_x64(int nr32, unsigned *flags_out)
{
    if (!index_ready)
        build_index();
    if (nr32 < 0 || nr32 >= SYS32_INDEX_SIZE) {
        if (flags_out)
            *flags_out = 0;
        return -1;
    }
    if (flags_out)
        *flags_out = i386_flags[nr32];
    return i386_to_x64[nr32];
}

size_t klee_sysnum_x64_to_i386(int nr64, int *out, size_t max)
{
    size_t n = 0;
    for (size_t i = 0; i < klee_sysnum32_table_len && n < max; i++) {
        const KleeSysnum32Entry *e = &klee_sysnum32_table[i];
        if (e->nr64 == nr64)
            out[n++] = e->nr32;
    }
    return n;
}
"""


def parse(path):
    nums = {}
    for m in re.finditer(r"#define\s+__NR_(\w+)\s+(\d+)", open(path).read()):
        nums[m.group(1)] = int(m.group(2))
    return nums


def main():
    n32 = parse(H32)
    n64 = parse(H64)
    rows = []
    for name, nr in sorted(n32.items(), key=lambda kv: kv[1]):
        flags = []
        if name in ALIASES:
            target, f = ALIASES[name]
            if f:
                flags.append(f)
        elif name in n64:
            target = name
            if name in OLDSTRUCT_SAME_NAME:
                flags.append("OLDSTRUCT")
        else:
            continue
        if target is None:
            x64 = -1
        elif target in n64:
            x64 = n64[target]
        else:
            continue
        rows.append((nr, name, x64, flags))

    out = sys.stdout
    out.write("/*\n * Klee - Userspace bwrap translation layer\n"
              " * i386 -> x86_64 syscall number map.  GENERATED by\n"
              " * scripts/gen_sysnum32.py from the kernel's unistd_32.h and\n"
              " * unistd_64.h; do not edit by hand.\n */\n")
    out.write('#include "syscall/sysnum32.h"\n\n')
    out.write("const KleeSysnum32Entry klee_sysnum32_table[] = {\n")
    for nr, name, x64, flags in rows:
        fl = " | ".join("KLEE_SYS32_" + f for f in flags) if flags else "0"
        out.write("    { %4d, %4d, %-22s }, /* %s */\n" % (nr, x64, fl, name))
    out.write("};\n\n")
    out.write("const size_t klee_sysnum32_table_len =\n"
              "    sizeof(klee_sysnum32_table) / sizeof(klee_sysnum32_table[0]);\n\n")
    out.write(LOOKUP)


if __name__ == "__main__":
    main()
